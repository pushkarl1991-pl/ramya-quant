"""
RAMYA GLOBAL FINTECH PLATFORM - Database Engine & ORM Models
Manages Clients, Universal Broker Connections, Multi-Currency Wallets, and 10% Fee Accounting.
"""

import time
from datetime import datetime
from sqlalchemy import create_engine, Column, Integer, String, Float, Boolean, DateTime, ForeignKey, Text
from sqlalchemy.orm import declarative_base, sessionmaker, relationship
from backend.config import settings

Base = declarative_base()
engine = create_engine(settings.DATABASE_URL, connect_args={"check_same_thread": False})
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)

class ClientUser(Base):
    __tablename__ = "client_users"
    
    id = Column(Integer, primary_key=True, index=True)
    full_name = Column(String(120), nullable=False)
    mobile_number = Column(String(20), unique=True, index=True, nullable=False)
    email = Column(String(120), unique=True, index=True, nullable=False)
    country = Column(String(60), default="India")
    referral_code = Column(String(50), unique=True, index=True, nullable=True)
    referred_by = Column(String(50), nullable=True)
    referral_points = Column(Integer, default=500)
    referral_earnings_inr = Column(Float, default=0.0)
    created_at = Column(DateTime, default=datetime.utcnow)
    is_active = Column(Boolean, default=True)
    
    # Relationships
    wallet = relationship("ClientWallet", back_populates="user", uselist=False)
    brokers = relationship("ClientBrokerConnection", back_populates="user")
    trades = relationship("TradeLedger", back_populates="user")

class ClientWallet(Base):
    __tablename__ = "client_wallets"
    
    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("client_users.id"), unique=True, nullable=False)
    inr_fuel_balance = Column(Float, default=0.0)      # Prepaid fuel in INR (for Indian brokers)
    usdt_fuel_balance = Column(Float, default=0.0)     # Prepaid fuel in USDT (for Global / Crypto / Forex)
    lifetime_gross_profit = Column(Float, default=0.0) # Total profit generated by bots for this user
    lifetime_commission_paid = Column(Float, default=0.0) # Total 10% fee settled to Master Treasury
    auto_pay_mandate_active = Column(Boolean, default=False)
    mandate_id = Column(String(100), nullable=True)
    status = Column(String(30), default="ACTIVE")      # ACTIVE, LOCKED_LOW_FUEL, SUSPENDED
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)
    
    user = relationship("ClientUser", back_populates="wallet")

class ClientBrokerConnection(Base):
    __tablename__ = "client_broker_connections"
    
    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("client_users.id"), nullable=False)
    broker_name = Column(String(50), nullable=False)   # DELTA, BINANCE, ZERODHA, DHAN, ANGEL, EXNESS, MT5, OCTAFX
    market_category = Column(String(30), nullable=False) # CRYPTO, MCX, INDIAN_EQUITY, FOREX
    api_key = Column(String(255), nullable=False)
    api_secret = Column(String(255), nullable=True)
    client_code = Column(String(100), nullable=True)   # For Dhan / Angel One / Shoonya
    trading_mode = Column(String(20), default="PAPER")  # PAPER (Simulated) or REAL (Real-Money)
    allocated_margin_pct = Column(Float, default=80.0) # 80% Max margin utilization
    selected_robot_id = Column(String(50), default="AUTO_AI_SELECTOR")
    is_connected = Column(Boolean, default=True)
    created_at = Column(DateTime, default=datetime.utcnow)
    
    user = relationship("ClientUser", back_populates="brokers")

class TradeLedger(Base):
    __tablename__ = "trade_ledger"
    
    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("client_users.id"), nullable=False)
    broker_name = Column(String(50), nullable=False)
    symbol = Column(String(30), nullable=False)
    market_category = Column(String(30), nullable=False) # CRYPTO, MCX, INDIAN_EQUITY, FOREX
    robot_name = Column(String(60), nullable=False)
    side = Column(String(10), nullable=False)          # BUY or SELL
    entry_price = Column(Float, nullable=False)
    exit_price = Column(Float, nullable=False)
    quantity = Column(Float, nullable=False)
    gross_pnl = Column(Float, nullable=False)
    net_pnl = Column(Float, nullable=False)
    commission_10pct = Column(Float, default=0.0)      # 10% Performance fee
    fee_settled = Column(Boolean, default=False)
    settled_from = Column(String(30), default="IN_APP_FUEL_WALLET") # IN_APP_FUEL_WALLET, UPI_AUTOPAY, BROKER_PAMM
    is_paper_trade = Column(Boolean, default=False)
    timestamp = Column(DateTime, default=datetime.utcnow)
    
    user = relationship("ClientUser", back_populates="trades")

class TreasurySettlementLog(Base):
    """Auditable tax and master bank credit log for all 10% fee receipts."""
    __tablename__ = "treasury_settlement_log"
    
    id = Column(Integer, primary_key=True, index=True)
    trade_id = Column(Integer, ForeignKey("trade_ledger.id"), nullable=True)
    user_id = Column(Integer, ForeignKey("client_users.id"), nullable=False)
    amount_inr = Column(Float, default=0.0)
    amount_usdt = Column(Float, default=0.0)
    payment_rail = Column(String(40), nullable=False)  # UPI_AUTOPAY, USDT_TRC20, USDT_POLYGON, RAZORPAY
    transaction_ref = Column(String(120), unique=True, nullable=False)
    tax_compliance_code = Column(String(60), default="GST_EXEMPT_SOFTWARE_FEE_18PCT")
    created_at = Column(DateTime, default=datetime.utcnow)

