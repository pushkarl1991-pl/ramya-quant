class VaultTransaction(Base):
    """Immutable ledger of all in/out transactions for Ramya Wallet (UPI, USDT, Foreign Wire, Bank withdrawals)."""
    __tablename__ = "vault_transactions"

    id = Column(Integer, primary_key=True, index=True)
    transaction_type = Column(String(50), nullable=False)  # COMMISSION_CREDIT, CLIENT_DEPOSIT, UPI_SCAN_PAYOUT, USDT_PAYOUT, BANK_WITHDRAWAL, CURRENCY_SWAP
    amount = Column(Float, nullable=False)
    currency = Column(String(10), default="INR")           # INR, USDT, USD, EUR, BTC
    party_ref = Column(String(120), nullable=False)        # Recipient UPI ID, USDT address, or Bank A/C
    purpose_note = Column(String(255), nullable=True)      # e.g. "Offshore Trader Return", "Founder Salary (Sec 44ADA)"
    ref_code = Column(String(100), unique=True, nullable=False)
    balance_after = Column(Float, nullable=False)
    tax_shield_status = Column(String(50), default="OFFSHORE_TAX_EXEMPT") # OFFSHORE_TAX_EXEMPT, SEC_44ADA_CLAIMED, GST_18_DOMESTIC
    status = Column(String(30), default="COMPLETED")
    timestamp = Column(DateTime, default=datetime.utcnow)

